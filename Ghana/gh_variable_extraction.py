# 15. ERA5 MONTHLY EXTRACTION
# ============================================================

def get_era5(

    year,

    month

):

    start = ee.Date.fromYMD(

        int(year),

        int(month),

        1

    )


    end = start.advance(

        1,

        'month'

    )


    era5 = (

        ee.ImageCollection(

            'ECMWF/ERA5_LAND/HOURLY'

        )

        .filterDate(

            start,

            end

        )

        .map(

            derive_era5

        )

    )


    monthly_max = (

        era5

        .max()

    )


    sample_points = (

        points_fc

        .filter(

            ee.Filter.eq(

                'year',

                int(year)

            )

        )

    )


    sampled = (

        monthly_max

        .sampleRegions(

            collection=

            sample_points,

            scale=11132,

            geometries=False

        )

    )


    result = geemap.ee_to_df(

        sampled

    )


    result['Month_Number'] = int(

        month

    )


    return result


