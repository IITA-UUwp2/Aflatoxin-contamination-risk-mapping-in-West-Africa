# 12. CHIRPS — MAXIMUM DAILY RAINFALL
# ============================================================
#
# Dataset:
# CHIRPS Daily
#
# Output:
# Maximum daily rainfall in each month
#
# Unit:
# mm/day
#
# ============================================================

def get_rainfall(

    year,

    month

):

    start = ee.Date.fromYMD(

        int(year),

        int(month),

        1

    )


    end = start.advance(

        1,

        'month'

    )


    images = (

        ee.ImageCollection(

            'UCSB-CHG/CHIRPS/DAILY'

        )

        .filterDate(

            start,

            end

        )

        .select(

            'precipitation'

        )

    )


    monthly_max = (

        images

        .max()

        .rename(

            'Rainfall_MaxDaily_mm_day'

        )

    )


    sample_points = (

        points_fc

        .filter(

            ee.Filter.eq(

                'year',

                int(year)

            )

        )

    )


    sampled = (

        monthly_max

        .sampleRegions(

            collection=

            sample_points,

            scale=5566,

            geometries=False

        )

    )


    result = geemap.ee_to_df(

        sampled

    )


    result['Month_Number'] = int(

        month

    )


    return result



