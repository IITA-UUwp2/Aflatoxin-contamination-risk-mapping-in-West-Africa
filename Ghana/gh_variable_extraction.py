# Extracting all other variaboles: Air Temperature:°C
# Relative Humidity: %
# Wind Speed: m/s
# Surface Pressure:hPa
# Soil Temperature:°C

def derive_era5(
    image
):
    # Temperature
    temperature = (
        image
        .select(
            'temperature_2m'
        )
        .subtract(
            273.15
        )
        .rename(
            'AirTemp_MaxDaily_degC'
        )
    )

    # Dew point
    dewpoint = (
        image
        .select(
            'dewpoint_temperature_2m'
        )
        .subtract(
            273.15
        )

    )


    # Relative humidity
    es = (
        temperature
        .multiply(
            17.625
        )
        .divide(
            temperature.add(
                243.04
            )
        )

        .exp()
    )

    ea = (

        dewpoint

        .multiply(

            17.625
        )
        .divide(
            dewpoint.add(
                243.04
            )
        )

        .exp()
    )

    relative_humidity = (
        ea
        .divide(
            es
        )

        .multiply(
            100
        )
        .clamp(

            0,

            100
        )

        .rename(

            'RH_MaxDaily_pct'
        )

    )

    # Wind

    u = (

        image

        .select(

            'u_component_of_wind_10m'

        )

    )


    v = (

        image

        .select(

            'v_component_of_wind_10m'

        )

    )


    wind_speed = (

        u

        .pow(2)

        .add(

            v.pow(2)

        )

        .sqrt()

        .rename(

            'WindSpeed_MaxDaily_m_s'

        )

    )


    # Pressure

    pressure = (

        image

        .select(

            'surface_pressure'

        )

        .divide(

            100

        )

        .rename(

            'SurfacePressure_MaxDaily_hPa'

        )

    )


    # Soil temperature

    soil_temperature = (

        image

        .select(

            'soil_temperature_level_1'

        )

        .subtract(

            273.15

        )

        .rename(

            'SoilTemp_MaxDaily_degC'

        )

    )


    return (

        temperature

        .addBands(

            relative_humidity

        )

        .addBands(

            wind_speed

        )

        .addBands(

            pressure

        )

        .addBands(

            soil_temperature

        )

    )


